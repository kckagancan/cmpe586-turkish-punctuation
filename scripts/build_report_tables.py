"""Build paper tables from public, verified aggregates; no data/model access."""

import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    ('clean-anchor', 'Clean'),
    *[(f'{family}-{level}', f'{label}, {level}')
      for family, label in [('case_loss', 'Case loss'), ('diacritic_loss', 'Diacritic loss'),
                            ('typo_swap', 'Interior swap'), ('combined', 'Combined')]
      for level in ('mild', 'medium', 'heavy')],
    ('case_loss_full', 'Full case loss'), ('diacritic_loss_full', 'Full diacritic loss'),
]
SOURCES = [
    'docs/held-out-test-aggregates.csv', 'docs/held-out-test-diagnostics.csv',
    'docs/held-out-test-input-coverage.csv', 'docs/held-out-test-condition-summary.json',
    'docs/held-out-test-cohort-summary.json', 'configs/held-out-test.json',
    'docs/case-loss-ablation-clean-validation.csv',
]


def contents():
    rows = list(csv.DictReader((ROOT / SOURCES[0]).open()))
    index = {(r['cohort'], r['arm_or_contrast'], r['condition_group'], r['metric']): r
             for r in rows}
    summary = json.loads((ROOT / SOURCES[3]).read_text())
    if summary['analysis_identity'] != 'e39f8803a6e6614363a6db97c1edce870757a2e909dec9dba5e93d0d9edc7f91':
        raise ValueError('Expected the completed held-out analysis.')
    if summary['raw_text_included'] or summary['model_inference_performed']:
        raise ValueError('Expected public aggregate-only analysis.')

    def metric(arm, condition, cohort='primary', key='punctuation_macro.f1'):
        row = index[cohort, arm, condition, key]
        factor = 100 if row['unit'] == 'fraction' else 1
        mean = factor * float(row['mean'])
        sd = factor * float(row['sample_sd']) if row['sample_sd'] else None
        return f'{mean:.4f}' + (rf' $\pm$ {sd:.4f}' if sd is not None else '')

    def table(name, header, rows, align):
        body = [rf'\newcommand{{\{name}}}{{%', r'\setlength{\tabcolsep}{5pt}',
                rf'\begin{{tabular}}{{{align}}}',
                r'\toprule', ' & '.join(header) + r' \\', r'\midrule']
        body += [' & '.join(row) + r' \\' for row in rows]
        return '\n'.join([*body, r'\bottomrule', r'\end{tabular}', '}', ''])

    text = '% Generated by scripts/build_report_tables.py; edit the source aggregates only.\n'
    for cohort, name in [('primary', 'PrimaryResults'), ('sensitivity', 'SensitivityResults')]:
        text += table(name, ['Condition', 'Published', 'Clean', 'Augmented', r'$\Delta$ (pp)'],
                      [[label, *[metric(arm, group, cohort) for arm in ('published', 'clean', 'augmented')],
                        metric('augmented_minus_clean', group, cohort)] for group, label in GROUPS],
                      'lrrrr')
    # Read the augmented reference from the exact seed586 condition, then
    # cross-check against the saved ablation score plus the paired delta.
    ablation_rows = []
    for group, label in [('clean-anchor', 'Clean'), ('case_loss-medium', 'Case loss, medium'),
                         ('diacritic_loss-medium', 'Diacritic loss, medium'),
                         ('typo_swap-medium', 'Interior swap, medium'), ('combined-medium', 'Combined, medium')]:
        without = float(index['primary', 'without_case_loss', group, 'punctuation_macro.f1']['mean']) * 100
        delta = float(index['primary', 'augmented_minus_without_case_loss', group, 'punctuation_macro.f1']['mean'])
        condition = group if group == 'clean-anchor' else group + '-seed586'
        augmented = summary['conditions']['augmented'][condition]['cohorts']['primary']['punctuation_macro']['f1'] * 100
        if abs(augmented - without - delta) > 1e-10:
            raise ValueError(f'Matched ablation contrast differs: {condition}')
        ablation_rows.append([label, f'{augmented:.4f}', f'{without:.4f}', f'{delta:.4f}'])
    text += table('AblationResults',
                  ['Condition', 'Augmented', 'Without case', r'$\Delta$ (pp)'],
                  ablation_rows, 'lrrr')
    class_rows = []
    for condition, label in [('clean-anchor', 'Clean'), ('combined-heavy', 'Combined, heavy')]:
        for mark in ('PERIOD', 'COMMA', 'QUESTION_MARK'):
            class_rows.append([label, mark.replace('_', r'\_'),
                               *[metric(arm, condition, key=f'per_class.{mark}.f1')
                                 for arm in ('clean', 'augmented')]])
    text += table('ClassResults', ['Input', 'Class', 'Clean F1', 'Augmented F1'], class_rows, 'llrr')
    diagnostics = list(csv.DictReader((ROOT / SOURCES[1]).open()))
    diagnostic_rows = []
    for condition, label in [('case_loss-heavy-seed586', 'Case loss, heavy'),
                             ('combined-heavy-seed586', 'Combined, heavy')]:
        for arm, arm_label in [('clean', 'Clean'), ('augmented', 'Augmented')]:
            counts = Counter()
            for row in diagnostics:
                if (row['cohort'], row['model'], row['condition'], row['outcome']) == (
                        'primary', arm, condition, 'new_error'):
                    counts[row['input_location']] += int(row['word_count'])
            diagnostic_rows.append([label, arm_label, str(counts['edited_word']),
                                    str(counts['unchanged_word_edited_context']),
                                    str(counts['unchanged_row'])])
    text += table('DiagnosticResults', ['Input', 'Model', 'Edited', 'Context', 'Unedited row'],
                  diagnostic_rows, 'llrrr')
    coverage_rows = []
    for row in csv.DictReader((ROOT / SOURCES[2]).open()):
        condition = row['condition']
        if condition in {'combined-mild-seed586', 'combined-medium-seed586', 'combined-heavy-seed586',
                         'case_loss_full', 'diacritic_loss_full'}:
            label = condition.replace('-seed586', '').replace('_', ' ').replace('-', ', ')
            coverage_rows.append([label.capitalize(), row['primary_changed_words'],
                                  f"{float(row['primary_changed_percent']):.4f}\\%"])
    text += table('CoverageResults', ['Input (seed586 where stochastic)', 'Changed words', 'Coverage'],
                  coverage_rows, 'lrr')
    histories = list(csv.DictReader((ROOT / SOURCES[6]).open()))
    history_index = {(r['model'], int(r['epoch'])): r for r in histories}
    history_rows = []
    for epoch in (1, 2, 3):
        values = []
        for arm in ('clean', 'augmented', 'augmented_without_case_loss'):
            row = history_index[arm, epoch]
            value = f"{100 * float(row['punctuation_macro_f1']):.4f}"
            values.append(r'\textbf{' + value + '}' if row['selected'] == 'True' else value)
        history_rows.append([str(epoch), history_index['clean', epoch]['global_step'], *values])
    text += table('TrainingHistory', ['Epoch', 'Updates', 'Clean', 'Augmented', 'Without case'],
                  history_rows, 'rrrrr')
    binding = {'version': 'paper-tables-v1', 'analysis_identity': summary['analysis_identity'],
               'run_identity': summary['run_identity'], 'training_or_inference_performed': False,
               'sources': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in SOURCES},
               'generated_tables_sha256': hashlib.sha256(text.encode()).hexdigest()}
    return text, json.dumps(binding, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify existing tables without writing.')
    args = parser.parse_args()
    tables, binding = contents()
    for name, text in [('tables.tex', tables), ('results-binding.json', binding)]:
        path = ROOT / 'report' / name
        if args.check:
            if path.read_text() != text:
                raise ValueError(f'Out-of-date paper artifact: {path}')
        else:
            path.write_text(text)
    print('Paper tables and public aggregate bindings match.' if args.check else 'Built paper tables from public aggregates.')


if __name__ == '__main__':
    main()
